#!/usr/bin/env python3
"""Build assets/served-constants.js — the single registry of every displayed constant.

v4 panel (2026-10-19): copy must never drift from the spec again, so every
number the surfaces show is read from this registry — the trust badge, the
twin band cutoffs, the region count, the twin percentile table, the guess
eligibility rule.

Sources (real data, stdlib only):
  assets/atlas_regions.json     -> region_count
  assets/twin_bands.json        -> twin band cutoffs/labels/blurbs
  assets/twin_explainer.json    -> twin pair count + percentile lookup table
  panel spec overlap@20 = 0.115 -> badge 12% (see note below)

Badge note: the trust badge says "This view keeps 12% of each player's 20
nearest neighborhoods from the model". The panel computed overlap@20 = 0.115
(exact, fraction of each sampled player's 20 nearest 64-d neighbors that stay
neighbors on the flat atlas map) -> 12% when rounded. 0.115 also keeps the
"about 1 in 9" parenthetical honest (1/0.115 = 8.7).

Any QA failure is a hard failure (non-zero exit).
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
A = lambda *p: str(ROOT.joinpath(*p))  # noqa: E731

OUT = A("assets", "served-constants.js")


def main():
    regions = json.load(open(A("assets", "atlas_regions.json"), encoding="utf-8"))["regions"]
    region_count = len(regions)
    assert region_count == 12, f"expected 12 regions, got {region_count}"

    bands_doc = json.load(open(A("assets", "twin_bands.json"), encoding="utf-8"))
    bands = bands_doc["bands"]
    cuts = [b["min"] for b in bands]
    assert cuts == [0.727, 0.663, 0.0], f"band cutoffs drifted: {cuts}"

    te = json.load(open(A("assets", "twin_explainer.json"), encoding="utf-8"))
    meta = te["_meta"]
    pair_count = sum(1 for k in te if not k.startswith("_"))
    pct_table = meta["pct_table"]
    assert len(pct_table) == 101, f"pct_table must have 101 entries, got {len(pct_table)}"
    assert pair_count >= 1000, f"expected 1000+ twin pairs, got {pair_count}"

    # Badge: overlap@20 = 0.115 exact (panel spec) -> 12%.
    overlap_at_20 = 0.115
    badge_pct = round(overlap_at_20 * 100)
    assert badge_pct == 12, f"badge drifted: {badge_pct}"

    js = """/* assets/served-constants.js — the single registry of displayed constants.
 *
 * GENERATED by pipeline/build_served_constants.py — do not hand-edit.
 * Every number the surfaces show lives here; the badge, the twin bands, and
 * the pages read from it, so copy can never drift from the spec again.
 */
(function () {
  'use strict';
  var C = {
    /* Trust badge: fraction of each sampled player's 20 nearest 64-d
     * neighbors that stay neighbors on the flat atlas map. overlap@20 =
     * 0.115 (exact, panel spec 2026-10-19) -> 12pct when rounded. */
    badge_overlap_at20: %s,
    badge_overlap_pct: %d,

    /* Twin bands: norm-referenced cutoffs on the 64-d twin similarity.
     * Strong = top third of all twin similarities on record. */
    twin_bands: %s,
    twin_band_definition: "top third of all %d twin similarities on record",
    twin_pair_count: %d,
    /* sim at each percentile 0..100 of the twin similarity distribution —
     * lets any surface headline the percentile from the sim alone. */
    twin_sim_percentiles: %s,
    twin_sim_interval_method: "bootstrap se of the 64-d cosine under resampling of the 64 embedding dims (reps=100, seed=20261019)",

    /* Atlas regions. */
    region_count: %d,

    /* Daily Court guess eligibility: a qualifying 2025-26 season —
     * 12+ games and 450+ total minutes (schedule-aware reliability gate from
     * pipeline/eligibility.py: ~15%% of schedule games, ~6%% of a 48-mpg
     * rotation baseline across the schedule, floor 450 minutes). */
    guess_rule: "Only players with a qualifying 2025-26 season (12+ games, 450+ total minutes)",
    guess_rule_short: "12+ games, 450+ minutes, 2025-26 season"
  };
  window.VHServedConstants = C;

  /* Stamp static placeholders: <span data-served-const="badge_overlap_pct">12</span>.
   * The inline fallback text is the same value, so no-JS still shows the truth. */
  function stamp() {
    try {
      var els = document.querySelectorAll('[data-served-const]');
      for (var i = 0; i < els.length; i++) {
        var key = els[i].getAttribute('data-served-const');
        if (key && C[key] !== undefined && C[key] !== null) els[i].textContent = C[key];
      }
    } catch (e) { /* the registry must never break a page */ }
  }
  if (typeof document !== 'undefined') {
    if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', stamp);
    else stamp();
  }
})();
""" % (
        overlap_at_20,
        badge_pct,
        json.dumps([{"min": b["min"], "label": b["label"], "blurb": b["blurb"]} for b in bands]),
        pair_count,
        pair_count,
        json.dumps(pct_table),
        region_count,
    )

    with open(OUT, "w", encoding="utf-8") as f:
        f.write(js)
    pub = OUT.replace(A("assets"), A("public", "assets"), 1)
    Path(pub).parent.mkdir(parents=True, exist_ok=True)
    with open(pub, "w", encoding="utf-8") as f:
        f.write(js)
    print(f"OK: {OUT}: badge {badge_pct}%, bands {cuts}, regions {region_count}, pairs {pair_count}")


if __name__ == "__main__":
    main()
