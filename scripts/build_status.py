#!/usr/bin/env python3
"""build_status.py -- regenerate the public /status page snapshot from repo evidence.

Reads only facts the repo can prove (git state, site_facts.json, the
served-model check, vercel.json headers). Unknowns are reported as
"unknown", stale as "last known" -- never invented.

Writes:
  assets/status.json   machine-readable snapshot
  status.html          replaces the <!--STATUS-SNAPSHOT--> marker with the
                       rendered snapshot (hand-written template above/below it)

Usage:
  python scripts/build_status.py            # regenerate
  python scripts/build_status.py --check     # fail if snapshot is stale

Stdlib only. ruff clean.
"""

from __future__ import annotations

import argparse
import html
import json
import re
import subprocess
import sys
from datetime import UTC, datetime, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SNAPSHOT_MARKER = "<!--STATUS-SNAPSHOT-->"
# The snapshot is regenerated by scheduled automation; a snapshot older than
# this means the pipeline stopped running, not that everything is fine.
MAX_SNAPSHOT_AGE_HOURS = 48
# A feed source whose last good tick is older than this is flagged stale and
# the Feed health header drops from ok to warn. Normal feed cadence is
# 30 s–5 min during the season, so 120 min of silence means the pipeline
# (not the page) is behind.
FEED_STALE_AFTER_MINUTES = 120
# The daily box pipeline (scripts/daily/run_daily.py) writes its own probes of
# cdn.nba.com here, one row per feed it read, each with its own freshness gate
# (stale_after_minutes: a daily feed is not stale two hours after it ran).
DAILY_RECEIPT = Path("assets") / "realtime" / "daily_pipeline.json"

# GitHub Actions workflow-annotation syntax (e.g. "::warning title=x::message").
# Stripped here so CI annotations never leak into user-facing HTML.
ANNOTATION_RE = re.compile(r"^::(warning|notice|error|debug)(?:\s+[^:]*)?::")


def clean_annotation(line: str) -> str:
    """Remove CI annotation syntax from a warning line for human readers."""
    text = ANNOTATION_RE.sub("", line).strip()
    if len(text) > 160:
        cut = text[:160].rsplit(" ", 1)[0]
        text = (cut or text[:160]) + "…"
    return text


def git(*args: str) -> str:
    try:
        return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, timeout=20).stdout.strip()
    except Exception:
        return ""


def served_model_state() -> dict:
    """Run the repo's own lineage check; capture pass/fail + warning lines."""
    try:
        proc = subprocess.run(
            [sys.executable, "scripts/check_served_model.py"],
            cwd=ROOT,
            capture_output=True,
            text=True,
            timeout=120,
        )
    except Exception as exc:
        return {"state": "unknown", "detail": f"check could not run: {exc}"}
    out = (proc.stdout + proc.stderr).strip()
    raw_warnings = [line for line in out.splitlines() if "warning" in line.lower() or "forced" in line.lower()]
    warnings = [clean_annotation(line) for line in raw_warnings]
    if proc.returncode == 0:
        return {
            "state": "pass",
            "detail": out.splitlines()[-1] if out else "check passed",
            "warnings": warnings[:4],
        }
    return {
        "state": "fail",
        "detail": out[-800:] if out else "check failed with no output",
        "warnings": warnings[:4],
    }


def site_facts() -> dict:
    path = ROOT / "assets" / "site_facts.json"
    if not path.exists():
        return {}
    try:
        return json.load(path.open(encoding="utf-8")).get("facts", {})
    except Exception:
        return {}


def csp_enforcing() -> str:
    try:
        cfg = json.load((ROOT / "vercel.json").open(encoding="utf-8"))
    except Exception:
        return "unknown"
    for rule in cfg.get("headers", []):
        for h in rule.get("headers", []):
            if h.get("key") == "Content-Security-Policy":
                return "enforcing"
            if h.get("key") == "Content-Security-Policy-Report-Only":
                return "report-only"
    return "unknown"


def _parse_tick(ts: object) -> datetime | None:
    """Parse an ISO-8601 last_good_tick; None when missing or unparsable."""
    if not ts or not isinstance(ts, str):
        return None
    try:
        dt = datetime.fromisoformat(ts.replace("Z", "+00:00"))
    except ValueError:
        return None
    return dt if dt.tzinfo else dt.replace(tzinfo=UTC)


def feed_health_snapshot() -> dict:
    """Read the deployed realtime feed-health snapshot (last-known, never live).

    This is the same evidence the standalone /feed-health page renders; the
    status page now carries it as its own card so only one surface exists.
    A down or missing snapshot is reported as unknown, never invented.

    Freshness gate: a source that still claims "ok" but whose last good tick
    is older than FEED_STALE_AFTER_MINUTES is demoted to "stale", and the
    card's overall state drops from ok to degraded (warn). Without this, a
    days-old snapshot renders "Overall ok" — a false green.
    """
    docs = []
    for rel in (Path("assets") / "realtime" / "feed_health.json", DAILY_RECEIPT):
        try:
            docs.append(json.load((ROOT / rel).open(encoding="utf-8")))
        except Exception:
            continue
    if not docs:
        return {
            "state": "unknown",
            "detail": "No feed-health snapshot found in the repo.",
            "updated_at": "unknown",
            "sources": [],
        }
    rows = []
    for doc in docs:
        sources = doc.get("sources", {}) or {}
        for name in sorted(sources):
            s = sources[name] or {}
            gate = s.get("stale_after_minutes")
            rows.append(
                {
                    "name": name,
                    "status": s.get("status", "unknown"),
                    "last_good_tick": s.get("last_good_tick") or "unknown",
                    "latency_ms": s.get("latency_ms"),
                    "consecutive_failures": s.get("consecutive_failures"),
                    "detail": s.get("detail") or "",
                    "stale_after_minutes": gate if isinstance(gate, int | float) and gate > 0 else FEED_STALE_AFTER_MINUTES,
                }
            )
    now = datetime.now(UTC)
    stale_names = []
    for r in rows:
        if r["status"] != "ok":
            continue
        gate = r["stale_after_minutes"]
        tick = _parse_tick(r["last_good_tick"])
        age_min = (now - tick).total_seconds() / 60 if tick else None
        if age_min is None or age_min > gate:
            r["status"] = "stale"
            why = (
                f"last good tick {age_min:.0f} min ago"
                if age_min is not None
                else "last good tick missing or unparsable"
            )
            r["detail"] = f"{r['detail']} [{why} — over the {gate:g}-min freshness gate]".strip()
            stale_names.append(r["name"])
    statuses = {r["status"] for r in rows}
    if not rows:
        state = "unknown"
    elif "down" in statuses or "error" in statuses:
        state = "down"
    elif "stale" in statuses or "degraded" in statuses:
        state = "degraded"
    else:
        state = "ok"
    detail = (
        "Realtime data-plane sources: uptime, lag, last-good-tick. "
        "This card reads the last deployed snapshot — staleness here "
        "means the pipeline (not the page) is behind. A source whose last "
        f"good tick is older than {FEED_STALE_AFTER_MINUTES} min (the daily "
        "cdn.nba.com rows: their own gate) is flagged stale and the header "
        "drops from ok to warn."
    )
    if stale_names:
        detail += f" Currently stale: {', '.join(sorted(stale_names))}."
    stamps = [d.get("updated_at") for d in docs if d.get("updated_at")]
    return {
        "state": state,
        "detail": detail,
        "updated_at": max(stamps) if stamps else "unknown",
        "sources": rows,
    }


def build() -> dict:
    facts = site_facts()
    model = served_model_state()
    feed = feed_health_snapshot()
    commit = git("rev-parse", "--short", "HEAD") or "unknown"
    commit_date = git("log", "-1", "--format=%ci") or "unknown"

    checks = []
    if model["state"] == "fail":
        checks.append(("Model serving", "bad", "lineage check failing"))
    elif model["state"] == "unknown":
        checks.append(("Model serving", "na", "check could not run"))
    elif model.get("warnings"):
        checks.append(("Model serving", "warn", "pass with lineage override flags"))
    else:
        checks.append(("Model serving", "ok", "lineage check passing"))
    checks.append(("Site facts", "ok" if facts else "na", f"{len(facts)} facts" if facts else "not built"))
    if feed["state"] == "down":
        checks.append(("Feed health", "bad", "one or more feed sources down"))
    elif feed["state"] == "degraded":
        checks.append(("Feed health", "warn", "feed stale — last good tick older than freshness gate"))
    elif feed["state"] == "unknown":
        checks.append(("Feed health", "na", "no feed snapshot"))
    else:
        checks.append(("Feed health", "ok", "all sources fresh"))

    overall = "operational"
    if any(s == "bad" for _, s, _ in checks):
        overall = "incident"
    elif any(s in ("warn", "na") for _, s, _ in checks):
        overall = "degraded"

    return {
        "generated_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "overall": overall,
        "deploy": {
            "commit": commit,
            "commit_date": commit_date,
            "csp": csp_enforcing(),
        },
        "data": {
            "model_name": facts.get("model_name", "unknown"),
            "model_built": facts.get("model_built", "unknown"),
            "seasons": f"{facts.get('season_first', '?')}–{facts.get('season_last', '?')}" if facts else "unknown",
            "player_seasons": facts.get("player_seasons", "unknown"),
            "players": facts.get("players", "unknown"),
        },
        "model_serving": {
            "state": model["state"],
            "detail": model.get("detail", "unknown"),
            "flags": model.get("warnings", []),
            "note": (
                "Lineage records a forced adoption of the July 2026 v5 "
                "incumbent; the original promote.py run files are not in "
                "this repo. Find the run files or order a replacement "
                "champion — the owner's decision."
            ),
        },
        "feed_health": feed,
        "incidents": [],
        "checks": [{"name": n, "state": s, "note": note} for n, s, note in checks],
    }


def render(snapshot: dict) -> str:
    e = html.escape

    def pill(state: str, label: str) -> str:
        cls = "pill" if state == "na" else f"pill pill--{state}"
        return f'<span class="{cls}">{e(label)}</span>'

    dot = {"operational": "ok", "degraded": "warn", "incident": "bad"}[snapshot["overall"]]
    banner_label = {
        "operational": "All systems operational",
        "degraded": "Degraded — see flags below",
        "incident": "Incident — see below",
    }[snapshot["overall"]]

    d = snapshot["deploy"]
    data = snapshot["data"]
    ms = snapshot["model_serving"]
    def row(k: str, v: object) -> str:
        v = "unknown" if v is None else v
        return f'<div class="st__row"><span class="st__k">{e(k)}</span><span class="st__v">{e(str(v))}</span></div>'

    fh = snapshot["feed_health"]
    fh_pill_state = {"ok": "ok", "degraded": "warn", "down": "bad", "unknown": "na"}[fh["state"]]
    fh_rows = []
    for s in fh.get("sources", []):
        s_pill = {"ok": "ok", "degraded": "warn", "stale": "warn", "down": "bad", "unknown": "na"}.get(s["status"], "na")
        latency = "unknown" if s["latency_ms"] is None else f'{s["latency_ms"]} ms'
        fails = (
            "unknown"
            if s["consecutive_failures"] is None
            else ("0" if s["consecutive_failures"] == 0 else f'{s["consecutive_failures"]} — needs attention')
        )
        fh_rows.append(
            '<div class="st__row"><span class="st__k">' + e(s["name"].replace("_", " ")) + "</span>"
            f'<span class="st__v">{pill(s_pill, s["status"])}</span></div>'
            + row("Last good tick", s["last_good_tick"])
            + row("Latency", latency)
            + row("Consecutive failures", fails)
        )
    fh_sources_html = "".join(fh_rows) if fh_rows else row("Sources", "none recorded")
    fh_html = (
        f'<section class="st__card" id="feed-health" aria-label="Feed health">'
        f'<h2>Feed health</h2>'
        f'<div class="st__row"><span class="st__k">Overall</span>'
        f'<span class="st__v">{pill(fh_pill_state, fh["state"])}</span></div>'
        f'{fh_sources_html}'
        f'<div class="st__row"><span class="st__k">Snapshot</span>'
        f'<span class="st__v">{e(str(fh["updated_at"]))}</span></div>'
        f'<p class="st__note">{e(fh["detail"])}</p>'
        f"</section>"
    )


    model_pill = {"pass": pill("ok", "pass"), "fail": pill("bad", "fail"), "unknown": pill("na", "unknown")}[
        ms["state"]
    ]
    flags = "".join(f"<li><code>{e(w)}</code></li>" for w in ms.get("flags", []))
    flags_html = f"<ul>{flags}</ul>" if flags else ""
    incidents = snapshot["incidents"]
    inc_html = (
        "<p>No incidents recorded.</p>"
        if not incidents
        else "".join(f"<p><b>{e(i.get('date', ''))}</b> — {e(i.get('summary', ''))}</p>" for i in incidents)
    )

    return f"""
  <div class="st__banner" role="status">
    <span class="st__dot st__dot--{dot}" aria-hidden="true"></span>
    <div>
      <strong>{e(banner_label)}</strong><br/>
      <span class="st__note">Snapshot {e(snapshot["generated_at"])} UTC</span>
    </div>
  </div>
  <div class="st__grid">
    <section class="st__card" aria-label="Site and deploy">
      <h2>Site &amp; deploy</h2>
      {row("Commit", d["commit"])}
      {row("Commit date", d["commit_date"])}
      {row("CSP", d["csp"])}
    </section>
    <section class="st__card" aria-label="Data freshness">
      <h2>Data</h2>
      {row("Model", data["model_name"])}
      {row("Model built", data["model_built"])}
      {row("Seasons", data["seasons"])}
      {row("Player-seasons", data["player_seasons"])}
      {row("Players", data["players"])}
    </section>
    <section class="st__card" aria-label="Model serving">
      <h2>Model serving</h2>
      <div class="st__row"><span class="st__k">Lineage check</span>
        <span class="st__v">{model_pill}</span></div>
      {row("Champion", "MTNN v5 (single-model policy)")}
      {flags_html}
      <p class="st__note">{e(ms["note"])}</p>
    </section>
    {fh_html}
    <section class="st__card" aria-label="Incident history">
      <h2>Incidents</h2>
      {inc_html}
    </section>
  </div>
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if the rendered snapshot is stale")
    args = ap.parse_args()

    page = ROOT / "status.html"
    if SNAPSHOT_MARKER not in page.read_text(encoding="utf-8"):
        print("FAIL status.html lost its snapshot marker")
        return 1

    snapshot = build()

    if args.check:
        stored_path = ROOT / "assets" / "status.json"
        current = page.read_text(encoding="utf-8")
        m = current.partition("Snapshot ")[2].split(" UTC")[0].strip()
        if not stored_path.exists() or not m:
            print("FAIL status snapshot missing — run scripts/build_status.py")
            return 1
        stored = json.load(stored_path.open(encoding="utf-8")).get("generated_at", "")
        if m != stored:
            print(
                f"FAIL status snapshot stale (page: {m or 'none'}, "
                f"status.json: {stored or 'none'}) — run scripts/build_status.py"
            )
            return 1
        try:
            age = datetime.now(UTC) - datetime.fromisoformat(stored)
        except ValueError:
            print(f"FAIL status snapshot has an unparsable timestamp ({stored}) — run scripts/build_status.py")
            return 1
        if age > timedelta(hours=MAX_SNAPSHOT_AGE_HOURS):
            days = age.total_seconds() / 86400
            print(
                f"FAIL status snapshot is {days:.1f} days old (max {MAX_SNAPSHOT_AGE_HOURS}h) — "
                "the scheduled regeneration stopped running. Run scripts/build_status.py "
                "and check the automation."
            )
            return 1
        print("OK   status snapshot current —", snapshot["generated_at"])
        return 0

    rendered = render(snapshot)

    (ROOT / "assets" / "status.json").write_text(json.dumps(snapshot, indent=2) + "\n", encoding="utf-8")
    text = page.read_text(encoding="utf-8")
    head, _, tail = text.partition(SNAPSHOT_MARKER)
    # drop any previously rendered snapshot between marker and the footer paragraph
    rest = tail
    foot = '<p class="st__foot">'
    fi = rest.find(foot)
    rest = rest[fi:] if fi != -1 else rest
    page.write_text(head + SNAPSHOT_MARKER + rendered + rest, encoding="utf-8")
    print("wrote assets/status.json + status.html snapshot —", snapshot["generated_at"], f"({snapshot['overall']})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
