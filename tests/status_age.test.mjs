// status.html: a snapshot older than the builder's own 48-hour limit says so.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';

const here = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const { ageSentence, apply, LIMIT_HOURS } = require(path.join(here, '..', 'assets', 'status-age.js'));

const H = 3600000;
const snap = '2026-10-23T15:18:55+00:00';
const t0 = Date.parse(snap);

test('47 hours old is within the limit', () => {
  assert.equal(ageSentence(snap, t0 + 47 * H), null);
});

test('exactly 48 hours old is within the limit (build_status.py: age > 48 h is stale)', () => {
  assert.equal(ageSentence(snap, t0 + 48 * H), null);
});

test('49 hours old gives a sentence with the age in days', () => {
  const s = ageSentence(snap, t0 + 49 * H);
  assert.equal(typeof s, 'string');
  assert.match(s, /2\.0 days old/);
});

test('18 days old (the committed snapshot on 2026-11-10) is reported in days', () => {
  assert.match(ageSentence(snap, Date.parse('2026-11-10T15:18:55Z')), /18\.0 days old/);
});

test('unparsable or missing snapshot says the age is unknown', () => {
  for (const bad of ['not a date', '', null, undefined, 42]) {
    assert.match(ageSentence(bad, t0), /age of this snapshot is unknown/);
  }
});

test('the JS limit equals MAX_SNAPSHOT_AGE_HOURS in scripts/build_status.py', () => {
  const py = readFileSync(path.join(here, '..', 'scripts', 'build_status.py'), 'utf8');
  const m = /^MAX_SNAPSHOT_AGE_HOURS\s*=\s*(\d+)/m.exec(py);
  assert.ok(m, 'MAX_SNAPSHOT_AGE_HOURS not found in build_status.py');
  assert.equal(LIMIT_HOURS, Number(m[1]));
});

test('status.html no longer states the schedule claim unconditionally', () => {
  const html = readFileSync(path.join(here, '..', 'status.html'), 'utf8');
  assert.ok(!/re-run on a schedule/.test(html));
  assert.match(html, /<script src="\/assets\/status-age\.js\?v=[0-9a-f]+"><\/script>/);
});

// ---- the DOM wiring, on a minimal stub document (no dependency) ----
const UNKNOWN = /age of this snapshot is unknown/;
const SCHEDULE = 'The underlying checks re-run on a schedule.';

function el(tag, cls) {
  const e = { tag, className: cls || '', children: [], parentNode: null, _text: '' };
  e.appendChild = (c) => { c.parentNode = e; e.children.push(c); return c; };
  Object.defineProperty(e, 'textContent', {
    get() { return e._text + e.children.map((c) => c.textContent).join(''); },
    set(v) { e._text = v; },
  });
  return e;
}
function textNode(t) { const e = el('#text'); e._text = t; return e; }

// withNote: banner has the builder's .st__note; note text given by `noteText`.
function makeDoc({ noteText, withNote = true, withBanner = true } = {}) {
  const banner = el('div', 'st__banner');
  const inner = el('div');
  banner.appendChild(inner);
  let note = null;
  if (withNote) { note = el('span', 'st__note'); note.textContent = noteText; inner.appendChild(note); }
  const foot = el('p', 'st__foot');
  foot.textContent = 'Snapshot generated by the builder.';
  const doc = {
    created: [],
    createElement(t) { const e = el(t); doc.created.push(e); return e; },
    createTextNode: textNode,
    // answers only the exact selectors the page uses
    querySelector(sel) {
      if (sel === '[role="status"]') return withBanner ? banner : null;
      if (sel === '.st__foot') return foot;
      return null;
    },
  };
  banner.querySelector = (sel) => (sel === '.st__note' ? note : sel === 'div' ? inner : null);
  return { doc, banner, inner, note, foot };
}
const noteFor = (iso) => 'Snapshot ' + iso + ' UTC';

test('stale (+18 d): the sentence is appended under the banner, the footer gains no schedule text', () => {
  const f = makeDoc({ noteText: noteFor(snap) });
  const before = f.foot.textContent;
  apply(f.doc, t0 + 18 * 24 * H);
  const last = f.inner.children[f.inner.children.length - 1];
  assert.equal(last.className, 'st__note');
  assert.equal(f.inner.children[f.inner.children.length - 2].tag, 'br');
  assert.match(last.textContent, /18\.0 days old, past the 48-hour limit/);
  assert.equal(f.foot.textContent, before);
  assert.ok(!f.foot.textContent.includes(SCHEDULE));
  assert.equal(f.note.textContent, noteFor(snap)); // original note untouched
});

test('within the limit (+47 h): banner unchanged, footer gains the schedule sentence', () => {
  const f = makeDoc({ noteText: noteFor(snap) });
  apply(f.doc, t0 + 47 * H);
  assert.equal(f.inner.children.length, 1);
  assert.equal(f.doc.created.length, 0);
  assert.ok(f.foot.textContent.endsWith(' ' + SCHEDULE));
});

test('unparsable timestamp: unknown sentence in the banner, no schedule text', () => {
  const f = makeDoc({ noteText: noteFor('not-a-date') });
  apply(f.doc, t0);
  const last = f.inner.children[f.inner.children.length - 1];
  assert.match(last.textContent, UNKNOWN);
  assert.ok(!f.foot.textContent.includes(SCHEDULE));
});

test('note without the Snapshot pattern: unknown sentence', () => {
  const f = makeDoc({ noteText: 'something else' });
  apply(f.doc, t0);
  assert.match(f.inner.children[f.inner.children.length - 1].textContent, UNKNOWN);
});

test('note missing: unknown sentence in the banner, nothing throws, no schedule text', () => {
  const f = makeDoc({ withNote: false });
  assert.doesNotThrow(() => apply(f.doc, t0));
  const last = f.inner.children[f.inner.children.length - 1];
  assert.match(last.textContent, UNKNOWN);
  assert.ok(!f.foot.textContent.includes(SCHEDULE));
});

test('no role=status banner: nothing happens', () => {
  const f = makeDoc({ noteText: noteFor(snap), withBanner: false });
  apply(f.doc, t0 + 100 * H);
  assert.equal(f.doc.created.length, 0);
  assert.ok(!f.foot.textContent.includes(SCHEDULE));
});

test('the script run as a page script uses the real clock (Date.now) and DOMContentLoaded', () => {
  const src = readFileSync(path.join(here, '..', 'assets', 'status-age.js'), 'utf8');
  const run = (nowMs, readyState) => {
    const f = makeDoc({ noteText: noteFor(snap) });
    const listeners = {};
    f.doc.readyState = readyState;
    f.doc.addEventListener = (n, fn) => { listeners[n] = fn; };
    class FakeDate extends Date { static now() { return nowMs; } }
    vm.runInNewContext(src, { document: f.doc, Date: FakeDate });
    if (readyState === 'loading') {
      assert.equal(f.doc.created.length, 0, 'nothing before DOMContentLoaded');
      listeners.DOMContentLoaded();
    }
    return f;
  };
  const stale = run(t0 + 18 * 24 * H, 'complete');
  assert.match(stale.inner.children[stale.inner.children.length - 1].textContent, /18\.0 days old/);
  assert.ok(!stale.foot.textContent.includes(SCHEDULE));
  const fresh = run(t0 + 47 * H, 'complete');
  assert.equal(fresh.inner.children.length, 1);
  assert.ok(fresh.foot.textContent.includes(SCHEDULE));
  const late = run(t0 + 18 * 24 * H, 'loading');
  assert.match(late.inner.children[late.inner.children.length - 1].textContent, /18\.0 days old/);
});
