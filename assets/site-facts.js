/* site-facts.js — fills [data-fact] elements from assets/site_facts.json,
   the canonical numbers sheet generated by scripts/build_site_facts.py.
   Static fallback text in the HTML is already the current value; this
   keeps pages true when the data is rebuilt. Fails silent by design. */
(function () {
  var els = document.querySelectorAll("[data-fact]");
  if (!els.length) return;
  fetch("/assets/site_facts.json?v=9f98acfd")
    .then(function (r) { return r.json(); })
    .then(function (d) {
      var facts = (d && d.facts) || {};
      els.forEach(function (el) {
        var v = facts[el.getAttribute("data-fact")];
        if (v == null) return;
        if (typeof v === "number") v = v.toLocaleString("en-US");
        var attr = el.getAttribute("data-fact-attr");
        if (attr) el.setAttribute(attr, v); else el.textContent = v;
      });
    })
    .catch(function () {});
})();
